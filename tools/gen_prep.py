# ---------------------------------------------------------------- 渲染
def render_list(items):
    if not items:
        return ""
    return '<ol class="prep-ol">' + "".join("<li>" + esc(x) + "</li>" for x in items) + "</ol>"

def render_report(blocks):
    out = []
    for title, items in blocks:
        if not title and not items:
            continue
        h = '<h5 class="prep-sub-h">' + esc(title) + "</h5>" if title else ""
        body = render_list(items)
        if not body and not h:
            continue
        out.append('<div class="prep-sub">' + h + body + "</div>")
    return "".join(out)

def render_exp(e):
    mine = "1" if e["week"] else "0"
    rep_text = []
    for _t, _items in e["report"]:
        if _t:
            rep_text.append(_t)
        rep_text.extend(_items)
    search_text = " ".join([e["no"], e["name"], e["week"], e["submit"], e["scope"]] +
                           e["focus"] + e["questions"] + rep_text)
    tags = []
    if e["week"]:
        tags.append('<span class="pm pm-week">' + esc(e["week"]) + "</span>")
    else:
        tags.append('<span class="pm pm-plain">不在我的课表</span>')
    tags.append('<span class="pm pm-submit">' + esc(e["submit"]) + "</span>")
    if e["scope"] != "全体":
        tags.append('<span class="pm pm-scope">' + esc(e["scope"]) + "</span>")

    parts = []
    parts.append('<details class="prep-card" id="' + e["id"] + '" data-mine="' + mine +
                 '" data-pre="' + e["pre"] + '" data-search="' +
                 html.escape(search_text, quote=True) + '">')
